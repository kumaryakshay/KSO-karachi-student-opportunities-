/** Get featured opportunities */
export const getFeaturedOpportunities = (): Opportunity[] =>
  mockOpportunities.filter((o) => o.isFeatured);

/** Get opportunities by category */
export const getOpportunitiesByCategory = (category: string): Opportunity[] =>
  mockOpportunities.filter((o) => o.category === category);

/** Search opportunities by title/org/tags */
export const searchOpportunities = (query: string): Opportunity[] => {
  const q = query.toLowerCase();
  return mockOpportunities.filter(
    (o) =>
      o.title.toLowerCase().includes(q) ||
      o.organization.toLowerCase().includes(q) ||
      o.tags.some((t) => t.toLowerCase().includes(q))
  );
};
